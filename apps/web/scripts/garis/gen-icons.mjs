// Generates src/components/icons/ from the locked prototype's drawings (garis/ui.js: IC, IC_FILL, ICON_LABELS):
// one file per icon, exporting the icon and, where the prototype has one, its two-tone service glyph.
// Run once when the drawings change, then format:
//   node scripts/garis/gen-icons.mjs <path to garis/ui.js> && pnpm exec prettier --write src/components/icons
// tests/garis-icons.test.mjs checks the generated set against tests/fixtures/garis-icons.json (the same drawings).
import fs from 'node:fs';
import path from 'node:path';

const [uiPath] = process.argv.slice(2);
if (!uiPath) throw new Error('usage: gen-icons.mjs <path to garis/ui.js>');
const src = fs.readFileSync(uiPath, 'utf8');
const literal = (name) => {
  const m = new RegExp(`const ${name} = (\\{[\\s\\S]*?\\n\\});`).exec(src);
  if (!m) throw new Error(`${name} not found`);
  return Function(`return (${m[1]})`)();
};
const IC = literal('IC');
const IC_FILL = literal('IC_FILL');
const LABELS = literal('ICON_LABELS');

const appDir = path.resolve(import.meta.dirname, '../..');
const out = path.join(appDir, 'src/components/icons');
const pascal = (k) => k.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());
const jsx = (svg) => svg.replace(/class="/g, 'className="');

for (const [key, drawing] of Object.entries(IC)) {
  const name = pascal(key);
  const fill = IC_FILL[key];
  const lines = [
    `// Generated by scripts/garis/gen-icons.mjs from the locked prototype (garis/ui.js). Don't edit by hand.`,
    `import { GarisIcon${fill ? ', GarisGlyph' : ''}, type IconProps } from './icon';`,
    ``,
    `/** ${LABELS[key] ?? key} */`,
    `export function Icon${name}(props: IconProps) {`,
    `  return <GarisIcon {...props}>${jsx(drawing)}</GarisIcon>;`,
    `}`,
  ];
  if (fill)
    lines.push(
      ``,
      `/** ${LABELS[key] ?? key}: the two-tone service glyph (an ink line over a gold fill), 24 px. */`,
      `export function Glyph${name}(props: Omit<IconProps, 'size'>) {`,
      `  return <GarisGlyph {...props}>${jsx(fill)}${jsx(drawing)}</GarisGlyph>;`,
      `}`,
    );
  fs.writeFileSync(path.join(out, `${key}.tsx`), lines.join('\n') + '\n');
}

const keys = Object.keys(IC);
const glyphKeys = Object.keys(IC_FILL);
const registry = [
  `// Generated by scripts/garis/gen-icons.mjs. Every Garis icon by key, for data-driven places (the service registry,`,
  `// search results). Screens that know their icon import it directly (\`import { IconBeranda } from`,
  `// '~/components/icons/beranda'\`), which keeps the rest out of their bundle.`,
  `import type { ComponentType } from 'react';`,
  `import type { IconProps } from './icon';`,
  ...keys.map(
    (k) =>
      `import { ${glyphKeys.includes(k) ? `Glyph${pascal(k)}, ` : ''}Icon${pascal(k)} } from './${k}';`,
  ),
  ``,
  `export const ICON_KEYS = [${keys.map((k) => `'${k}'`).join(', ')}] as const;`,
  `export type IconKey = (typeof ICON_KEYS)[number];`,
  `export const GLYPH_KEYS = [${glyphKeys.map((k) => `'${k}'`).join(', ')}] as const;`,
  `export type GlyphKey = (typeof GLYPH_KEYS)[number];`,
  ``,
  `export const ICONS: Record<IconKey, ComponentType<IconProps>> = {`,
  ...keys.map((k) => `  ${/-/.test(k) ? `'${k}'` : k}: Icon${pascal(k)},`),
  `};`,
  ``,
  `export const GLYPHS: Record<GlyphKey, ComponentType<Omit<IconProps, 'size'>>> = {`,
  ...glyphKeys.map((k) => `  ${k}: Glyph${pascal(k)},`),
  `};`,
  ``,
  `/** What each icon means, as the prototype's design-system page names it. */`,
  `export const ICON_LABELS: Record<IconKey, string> = {`,
  ...keys.map((k) => `  ${/-/.test(k) ? `'${k}'` : k}: ${JSON.stringify(LABELS[k] ?? k)},`),
  `};`,
];
fs.writeFileSync(path.join(out, 'registry.ts'), registry.join('\n') + '\n');

// The drawings, for the unit test (so CI can check the components without the prototype's source).
fs.mkdirSync(path.join(appDir, 'tests/fixtures'), { recursive: true });
fs.writeFileSync(
  path.join(appDir, 'tests/fixtures/garis-icons.json'),
  JSON.stringify({ IC, IC_FILL, ICON_LABELS: LABELS }, null, 2) + '\n',
);
console.log(`${keys.length} icons, ${glyphKeys.length} glyphs`);
