// The second half of `pnpm --filter web api`: rewrites the client openapi-typescript-codegen just wrote in
// src/api/generated so each API operation is its own file. A bundler puts a whole file in one chunk, so with one class
// per tag every page loaded every operation of that tag the entry used (docs/adr/0022-*). This writes
// `operations/<operationId>.ts` (the method's own code, calling the app's `http` from src/api/http.ts) and
// `operations/index.ts`, then removes `services/`, `ApiClient.ts` and the request class only it used, with their exports, so there is one way to call
// the API. It needs the generator's fresh output, so run it only through `pnpm --filter web api`.
import fs from 'node:fs';
import path from 'node:path';
import ts from 'typescript';

const generated = path.resolve(import.meta.dirname, '../src/api/generated');
const servicesDir = path.join(generated, 'services');
const operationsDir = path.join(generated, 'operations');

const HEADER = `/* generated by apps/web/scripts/api-operations.mjs from openapi-typescript-codegen's output -- do not edit */
/* istanbul ignore file */
/* tslint:disable */
/* eslint-disable */
`;

function fail(message) {
  console.error(`api-operations: ${message}`);
  process.exit(1);
}

if (!fs.existsSync(servicesDir))
  fail(`${servicesDir} is missing: run the whole \`pnpm --filter web api\``);

/** Removes `by` spaces from the start of every line (the method was indented inside its class). */
const dedent = (text, by) =>
  text
    .split('\n')
    .map((l) => (l.startsWith(' '.repeat(by)) ? l.slice(by) : l))
    .join('\n');

const operations = new Map();

for (const file of fs.readdirSync(servicesDir).sort()) {
  const servicePath = path.join(servicesDir, file);
  const text = fs.readFileSync(servicePath, 'utf8');
  const source = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true);

  /** Every type the service file imports, with its line, so an operation imports only what it names. */
  const imports = source.statements
    .filter(ts.isImportDeclaration)
    .flatMap((d) =>
      d.importClause.namedBindings.elements.map((e) => ({
        name: e.name.text,
        line: `import type { ${e.name.text} } from ${d.moduleSpecifier.getText(source)};`,
      })),
    );
  const service = source.statements.find(ts.isClassDeclaration);
  if (!service) fail(`${file} has no class`);

  for (const member of service.members) {
    if (ts.isConstructorDeclaration(member)) continue;
    if (!ts.isMethodDeclaration(member) || !member.body)
      fail(`${file}: unexpected member ${member.getText(source).slice(0, 60)}`);
    const name = member.name.getText(source);
    if (operations.has(name))
      fail(`${name} is in ${operations.get(name).file} and ${file}`);

    // The method's JSDoc, then `public name(params): Return { body }` as a function.
    const docs = ts
      .getJSDocCommentsAndTags(member)
      .filter(ts.isJSDoc)
      .map((d) => dedent(d.getText(source), 2));
    const signature = text.slice(
      member.name.getEnd(),
      member.body.getStart(source),
    );
    const body = member.body
      .getText(source)
      .replaceAll('this.httpRequest.request(', 'http.request(');
    if (body.includes('this.')) fail(`${file} ${name}: unexpected \`this.\``);
    const code = dedent(`export function ${name}${signature}${body}`, 2);

    const used = imports
      .filter(
        (i) =>
          i.name !== 'BaseHttpRequest' &&
          new RegExp(`\\b${i.name}\\b`).test(code),
      )
      .map((i) => i.line);
    operations.set(name, {
      file,
      text: `${HEADER}${used.join('\n')}\nimport { http } from '../../http';\n${docs.join('\n')}\n${code}\n`,
    });
  }
}

fs.rmSync(operationsDir, { recursive: true, force: true });
fs.mkdirSync(operationsDir);
const names = [...operations.keys()].sort();
for (const name of names)
  fs.writeFileSync(
    path.join(operationsDir, `${name}.ts`),
    operations.get(name).text,
  );
fs.writeFileSync(
  path.join(operationsDir, 'index.ts'),
  `${HEADER}${names.map((n) => `export { ${n} } from './${n}';`).join('\n')}\n`,
);

// FetchHttpRequest is the generator's default for `ApiClient`; every operation uses src/api/http.ts instead.
fs.rmSync(servicesDir, { recursive: true });
fs.rmSync(path.join(generated, 'ApiClient.ts'));
fs.rmSync(path.join(generated, 'core/FetchHttpRequest.ts'));
const indexPath = path.join(generated, 'index.ts');
fs.writeFileSync(
  indexPath,
  fs
    .readFileSync(indexPath, 'utf8')
    .split('\n')
    .filter((l) => !/from '\.\/(ApiClient|services\/)/.test(l))
    .join('\n')
    .replace(/\n{3,}/g, '\n\n'),
);
console.log(`api-operations: ${names.length} operations written`);
